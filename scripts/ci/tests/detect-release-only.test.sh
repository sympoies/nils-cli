#!/usr/bin/env bash
set -euo pipefail

repo_root="$(git rev-parse --show-toplevel 2>/dev/null || true)"
if [[ -z "$repo_root" || ! -d "$repo_root" ]]; then
  echo "error: must run inside the nils-cli git work tree" >&2
  exit 2
fi

script="$repo_root/scripts/ci/detect-release-only.sh"
if [[ ! -f "$script" ]]; then
  echo "FAIL: missing release-only detector: $script" >&2
  exit 1
fi

echo "== system bash parser compatibility =="
if [[ ! -x /bin/bash ]]; then
  echo "FAIL: /bin/bash is required for release detector compatibility" >&2
  exit 1
fi
/bin/bash -n "$script"
echo "ok: release-only detector parses with /bin/bash"

producer_script="$repo_root/scripts/ci/prepare-release-bump.sh"
if [[ ! -f "$producer_script" ]]; then
  echo "FAIL: missing canonical release producer: $producer_script" >&2
  exit 1
fi

tmp_root="$(mktemp -d "${TMPDIR:-/tmp}/detect-release-only.XXXXXX")"
trap 'rm -rf "$tmp_root"' EXIT

sha256_file() {
  local path="$1"
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$path" | awk '{print $1}'
  else
    shasum -a 256 "$path" | awk '{print $1}'
  fi
}

replace_text() {
  local old="$1"
  local new="$2"
  shift 2
  python3 - "$old" "$new" "$@" <<'PY'
import pathlib
import sys

old, new, *paths = sys.argv[1:]
for raw_path in paths:
    path = pathlib.Path(raw_path)
    path.write_text(path.read_text().replace(old, new))
PY
}

write_base_fixture() {
  local dir="$1"
  mkdir -p "$dir/crates/common" "$dir/crates/tool"
  git -C "$dir" init -q
  git -C "$dir" config user.name "Release CI Test"
  git -C "$dir" config user.email "release-ci@example.test"

  cat >"$dir/Cargo.toml" <<'EOF'
[workspace]
members = ["crates/common", "crates/tool"]
resolver = "2"

[workspace.package]
version = "1.2.3"

[workspace.dependencies]
nils-common = { path = "crates/common", version = "1.2.3" }
EOF
  cat >"$dir/crates/common/Cargo.toml" <<'EOF'
[package]
name = "nils-common"
version = "1.2.3"
edition = "2024"
EOF
  cat >"$dir/crates/tool/Cargo.toml" <<'EOF'
[package]
name = "nils-tool"
version = "1.2.3"
edition = "2024"

[dependencies]
nils-common = { workspace = true }
EOF
  cat >"$dir/Cargo.lock" <<'EOF'
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "nils-common"
version = "1.2.3"

[[package]]
name = "nils-tool"
version = "1.2.3"
dependencies = [
 "nils-common 1.2.3",
]
EOF
  cat >"$dir/README.md" <<'EOF'
Release with `git tag -a v1.2.3` and `git push origin v1.2.3`.
EOF
  local lock_sha
  lock_sha="$(sha256_file "$dir/Cargo.lock")"
  printf "Cargo.lock sha256: \`%s\`\n" "$lock_sha" >"$dir/THIRD_PARTY_LICENSES.md"
  printf "Cargo.lock sha256: \`%s\`\n" "$lock_sha" >"$dir/THIRD_PARTY_NOTICES.md"

  git -C "$dir" add .
  git -C "$dir" commit -q -m "chore: seed fixture"
}

write_release_commit() {
  local dir="$1"
  local old_lock_sha
  old_lock_sha="$(sha256_file "$dir/Cargo.lock")"

  replace_text "1.2.3" "1.2.4" \
    "$dir/Cargo.toml" \
    "$dir/crates/common/Cargo.toml" \
    "$dir/crates/tool/Cargo.toml" \
    "$dir/Cargo.lock" \
    "$dir/README.md"

  local new_lock_sha
  new_lock_sha="$(sha256_file "$dir/Cargo.lock")"
  replace_text "$old_lock_sha" "$new_lock_sha" \
    "$dir/THIRD_PARTY_LICENSES.md" \
    "$dir/THIRD_PARTY_NOTICES.md"

  git -C "$dir" add .
  git -C "$dir" commit -q -m "chore(release): bump cli versions to 1.2.4"
}

detect() {
  local dir="$1"
  shift
  (cd "$dir" && bash "$script" "$@")
}

assert_verdict() {
  local label="$1"
  local expected="$2"
  local dir="$3"
  shift 3
  local actual
  actual="$(detect "$dir" "$@")"
  if [[ "$actual" != "$expected" ]]; then
    echo "FAIL: $label"
    echo "  expected: $expected"
    echo "  actual:   $actual"
    exit 1
  fi
  echo "ok: $label ($expected)"
}

canonical="$tmp_root/canonical"
write_base_fixture "$canonical"
base_sha="$(git -C "$canonical" rev-parse HEAD)"
write_release_commit "$canonical"
head_sha="$(git -C "$canonical" rev-parse HEAD)"

assert_verdict "canonical release commit" true "$canonical" \
  --base "$base_sha" --head "$head_sha" --branch chore/release-1-2-4

merge_group="$tmp_root/merge-group"
write_base_fixture "$merge_group"
merge_base_sha="$(git -C "$merge_group" rev-parse HEAD)"
git -C "$merge_group" checkout -q -b chore/release-1-2-4
write_release_commit "$merge_group"
git -C "$merge_group" commit -q --amend \
  -m "chore(release): bump cli versions to 1.2.4 (#2423)"
merge_group_head="$(git -C "$merge_group" rev-parse HEAD)"
assert_verdict "bump-only merge group" true "$merge_group" \
  --base "$merge_base_sha" --head "$merge_group_head" --merge-group

mixed_merge_group="$tmp_root/mixed-merge-group"
cp -R "$merge_group" "$mixed_merge_group"
printf 'unrelated\n' >"$mixed_merge_group/extra.txt"
git -C "$mixed_merge_group" add extra.txt
git -C "$mixed_merge_group" commit -q --amend --no-edit
assert_verdict "mixed squash merge group" false "$mixed_merge_group" \
  --base "$merge_base_sha" --head HEAD --merge-group

multi_commit_merge_group="$tmp_root/multi-commit-merge-group"
cp -R "$merge_group" "$multi_commit_merge_group"
git -C "$multi_commit_merge_group" commit -q --allow-empty -m "chore: another queued change"
assert_verdict "multi-commit merge group" false "$multi_commit_merge_group" \
  --base "$merge_base_sha" --head HEAD --merge-group

echo "== protected checker revalidates merge-group mode =="
checker_repo="$merge_group"
mkdir -p "$checker_repo/scripts/ci" "$checker_repo/scripts"
cp "$repo_root/scripts/ci/release-only-checks.sh" \
  "$checker_repo/scripts/ci/release-only-checks.sh"
for helper in workspace-version-lockstep.sh publish-order-audit.sh; do
  printf '%s\n' '#!/usr/bin/env bash' 'exit 0' >"$checker_repo/scripts/ci/$helper"
done
printf '%s\n' '#!/usr/bin/env bash' 'exit 0' \
  >"$checker_repo/scripts/generate-third-party-artifacts.sh"
fake_bin="$tmp_root/fake-bin"
mkdir -p "$fake_bin"
printf '%s\n' '#!/usr/bin/env bash' 'exit 0' >"$fake_bin/cargo"
chmod +x "$fake_bin/cargo"
protected_dir="$tmp_root/protected-policy"
mkdir -p "$protected_dir"
protected_detector="$protected_dir/detect-release-only.sh"
detector_args="$tmp_root/detector-args"
cat >"$protected_detector" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$@" >"$DETECTOR_ARGS"
exec /bin/bash "$REAL_DETECTOR" "$@"
EOF
chmod +x "$protected_detector"
(
  cd "$checker_repo"
  RELEASE_ONLY_DETECTOR="$protected_detector" \
    DETECTOR_ARGS="$detector_args" REAL_DETECTOR="$script" \
    PATH="$fake_bin:$PATH" \
    /bin/bash scripts/ci/release-only-checks.sh \
      --base "$merge_base_sha" --head "$merge_group_head" --merge-group
)
if ! rg -q --fixed-strings -- "--merge-group" "$detector_args"; then
  echo "FAIL: protected checker forwards merge-group mode to the detector" >&2
  exit 1
fi
echo "ok: protected checker forwards merge-group mode to the detector"
assert_verdict "branch must match the target version" false "$canonical" \
  --base "$base_sha" --head "$head_sha" --branch chore/release-1-2-5
assert_verdict "invalid base fails closed" false "$canonical" \
  --base "$(printf '0%.0s' {1..40})" --head "$head_sha" --branch chore/release-1-2-4

extra="$tmp_root/extra"
cp -R "$canonical" "$extra"
printf 'unrelated\n' >"$extra/extra.txt"
git -C "$extra" add extra.txt
git -C "$extra" commit -q --amend --no-edit
assert_verdict "extra changed file" false "$extra" \
  --base "$base_sha" --head HEAD --branch chore/release-1-2-4

for policy_path in \
  .github/workflows/ci.yml \
  .github/scripts/release-ci-gate.cjs \
  scripts/ci/detect-release-only.sh \
  scripts/ci/release-only-checks.sh; do
  policy_name="${policy_path//\//-}"
  policy_tamper="$tmp_root/policy-${policy_name}"
  cp -R "$canonical" "$policy_tamper"
  mkdir -p "$policy_tamper/$(dirname "$policy_path")"
  printf 'untrusted policy override\n' >"$policy_tamper/$policy_path"
  git -C "$policy_tamper" add "$policy_path"
  git -C "$policy_tamper" commit -q --amend --no-edit
  assert_verdict "policy override ${policy_path}" false "$policy_tamper" \
    --base "$base_sha" --head HEAD --branch chore/release-1-2-4
done

partial="$tmp_root/partial"
cp -R "$canonical" "$partial"
replace_text 'version = "1.2.4"' 'version = "1.2.3"' "$partial/crates/common/Cargo.toml"
git -C "$partial" add crates/common/Cargo.toml
git -C "$partial" commit -q --amend --no-edit
assert_verdict "partial manifest bump" false "$partial" \
  --base "$base_sha" --head HEAD --branch chore/release-1-2-4

wrong_subject="$tmp_root/wrong-subject"
cp -R "$canonical" "$wrong_subject"
git -C "$wrong_subject" commit -q --amend -m "chore: update versions"
assert_verdict "non-canonical commit subject" false "$wrong_subject" \
  --base "$base_sha" --head HEAD --branch chore/release-1-2-4

two_commits="$tmp_root/two-commits"
cp -R "$canonical" "$two_commits"
git -C "$two_commits" commit -q --allow-empty -m "chore: second commit"
assert_verdict "more than one commit" false "$two_commits" \
  --base "$base_sha" --head HEAD --branch chore/release-1-2-4

echo "== canonical producer integration =="
producer_repo="$tmp_root/producer"
git clone -q --shared "$repo_root" "$producer_repo"
git -C "$producer_repo" config user.name "Release CI Test"
git -C "$producer_repo" config user.email "release-ci@example.test"
# Newer Git detaches automatic maintenance after a commit. A detached
# maintenance run still writing into this clone makes the EXIT trap's rm -rf
# fail with "Directory not empty" after the test has passed.
git -C "$producer_repo" config maintenance.auto false
git -C "$producer_repo" config gc.auto 0

# Model a non-release PR that changes the lockfile without changing the
# third-party inventory. Its recorded artifact digests still describe the
# previous lockfile, even when this suite runs from a clean release checkout.
printf '\n# Non-release lockfile change.\n' >>"$producer_repo/Cargo.lock"

# This suite verifies release-only classification, not Cargo's registry
# resolver. Keep the producer fixture deterministic under an empty Cargo home
# by replacing its Cargo operations with the lockfile-only behavior that the
# detector expects from a workspace version refresh.
fixture_bin="$tmp_root/producer-bin"
mkdir -p "$fixture_bin"
cat >"$fixture_bin/cargo" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
if [[ "${1:-}" != update || "${2:-}" != --workspace ]]; then
  echo "unexpected cargo invocation in release-only fixture: $*" >&2
  exit 2
fi
python3 - <<'PY'
import pathlib
import re

root = pathlib.Path.cwd()
root_manifest = (root / "Cargo.toml").read_text()
new_version = re.search(
    r'(?ms)^\[workspace[.]package\].*?^version\s*=\s*"([^"]+)"',
    root_manifest,
).group(1)
names = set()
for manifest in [root / "Cargo.toml", *sorted((root / "crates").glob("*/Cargo.toml"))]:
    section = None
    for line in manifest.read_text().splitlines():
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            section = stripped.strip("[]")
        elif section == "package":
            match = re.match(r'\s*name\s*=\s*"([^"]+)"', line)
            if match:
                names.add(match.group(1))
                break

lock = (root / "Cargo.lock").read_text()
blocks = re.split(r'(?=^\[\[package\]\]\s*$)', lock, flags=re.M)
old_version = None
for block in blocks:
    if not block.startswith("[[package]]") or "\nsource = " in block:
        continue
    name = re.search(r'^name\s*=\s*"([^"]+)"\s*$', block, re.M)
    version = re.search(r'^version\s*=\s*"([^"]+)"\s*$', block, re.M)
    if name and name.group(1) in names and version:
        old_version = version.group(1)
        break
if old_version is None:
    raise SystemExit("workspace packages are missing from Cargo.lock")
for index, block in enumerate(blocks):
    if not block.startswith("[[package]]"):
        continue
    name = re.search(r'^name\s*=\s*"([^"]+)"\s*$', block, re.M)
    if name and name.group(1) in names and "\nsource = " not in block:
        blocks[index] = re.sub(
            rf'(^version\s*=\s*)"{re.escape(old_version)}"',
            rf'\g<1>"{new_version}"', block, count=1, flags=re.M,
        )
lock = "".join(blocks)
for name in names:
    lock = re.sub(
        rf'(?m)^(\s*"{re.escape(name)} ){re.escape(old_version)}("\s*,?\s*)$',
        rf'\g<1>{new_version}\g<2>', lock,
    )
(root / "Cargo.lock").write_text(lock)
PY
EOF
chmod +x "$fixture_bin/cargo"

# Preserve the checked-in generated artifact contents while updating only the
# lockfile digest. Their generator is separately covered by its own tests.
cat >"$producer_repo/scripts/generate-third-party-artifacts.sh" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
python3 - <<'PY'
import hashlib
import pathlib
import re

root = pathlib.Path.cwd()
lock_hash = hashlib.sha256((root / "Cargo.lock").read_bytes()).hexdigest()
for name in ("THIRD_PARTY_LICENSES.md", "THIRD_PARTY_NOTICES.md"):
    path = root / name
    text = path.read_text()
    path.write_text(re.sub(r'(?m)(Cargo.lock SHA256: `)[0-9a-f]+(`)', rf'\g<1>{lock_hash}\g<2>', text))
PY
EOF
chmod +x "$producer_repo/scripts/generate-third-party-artifacts.sh"

# The detector permits only replacing the baseline lockfile's actual digest.
# Normalize the fixture before capturing that baseline: a non-release checkout
# can legitimately have stale artifact digests, whose repair is not bump-only.
(
  cd "$producer_repo"
  bash scripts/generate-third-party-artifacts.sh --write
)

# Local validation runs before this change is committed, so copy the current
# producer into the clone and make it part of the immutable fixture baseline.
cp "$producer_script" \
  "$producer_repo/scripts/ci/prepare-release-bump.sh"
git -C "$producer_repo" add \
  Cargo.lock THIRD_PARTY_LICENSES.md THIRD_PARTY_NOTICES.md \
  scripts/ci/prepare-release-bump.sh \
  scripts/generate-third-party-artifacts.sh
if ! git -C "$producer_repo" diff --cached --quiet; then
  git -C "$producer_repo" commit -q --amend --no-edit
fi

producer_base="$(git -C "$producer_repo" rev-parse HEAD)"
producer_version="$(python3 - "$producer_repo/Cargo.toml" <<'PY'
import pathlib
import re
import sys

text = pathlib.Path(sys.argv[1]).read_text()
match = re.search(r'(?ms)^\[workspace[.]package\].*?^version\s*=\s*"(\d+)\.(\d+)\.(\d+)"', text)
if not match:
    raise SystemExit("workspace version missing")
major, minor, patch = map(int, match.groups())
print(f"{major}.{minor}.{patch + 1}")
PY
)"
(
  cd "$producer_repo"
  PATH="$fixture_bin:$PATH" \
    CARGO_HOME="$tmp_root/empty-cargo-home" \
    CARGO_NET_OFFLINE=true \
    bash \
    scripts/ci/prepare-release-bump.sh \
    --version "$producer_version" \
    --prepare-only
)
git -C "$producer_repo" add \
  Cargo.toml Cargo.lock README.md THIRD_PARTY_LICENSES.md THIRD_PARTY_NOTICES.md \
  crates/*/Cargo.toml
git -C "$producer_repo" commit -q \
  -m "chore(release): bump cli versions to ${producer_version}"
producer_head="$(git -C "$producer_repo" rev-parse HEAD)"
assert_verdict "real producer output from non-release baseline" true "$producer_repo" \
  --base "$producer_base" \
  --head "$producer_head" \
  --branch "chore/release-${producer_version//./-}"

echo
echo "PASS: detect-release-only.test.sh"
